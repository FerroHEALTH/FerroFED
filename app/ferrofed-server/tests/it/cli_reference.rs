//! The book's command-line reference, generated from the `clap` definition
//! of [`Cli`]: one section per visible command with its long help.
//!
//! `the_book_holds_the_current_cli_reference` fails when the committed page
//! differs from what the definition renders; `write_the_cli_reference`
//! (ignored, run with `cargo nextest run -p ferrofed-server --test it
//! --run-ignored only cli_reference`) writes the page again. No
//! specification governs the page: our own design.

use std::error::Error;
use std::path::PathBuf;

use clap::{Command, CommandFactory as _};
use ferrofed_server::cli::Cli;

type TestResult = Result<(), Box<dyn Error>>;

/// The page, relative to the workspace root.
const PAGE: &str = "website/book/src/reference/cli.md";

/// The help width, fixed so the page does not depend on the terminal.
const WIDTH: usize = 100;

/// Returns the page's path.
fn page_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(PAGE)
}

/// Appends the section of `command`, reached as `path`, and of each visible
/// subcommand below it.
fn section(out: &mut String, path: &str, command: &mut Command) {
    let help = command.render_long_help().to_string();
    for piece in ["## `", path, "`\n\n```text\n", help.trim_end(), "\n```\n\n"] {
        out.push_str(piece);
    }
    for sub in command
        .get_subcommands_mut()
        .filter(|sub| !sub.is_hide_set() && sub.get_name() != "help")
    {
        let below = [path, sub.get_name()].join(" ");
        section(out, &below, sub);
    }
}

/// The page's first lines: the generated banner and the two SPDX lines, each
/// tag split so this file's own header stays the only one it carries.
const HEADER: [&str; 3] = [
    "<!-- @generated by the ferrofed-server test cli_reference from the clap definition. DO NOT EDIT. -->",
    concat!("<!-- SPDX-", "FileCopyrightText: Cadasto B.V. -->"),
    concat!("<!-- SPDX-", "License-Identifier: BUSL-1.1 -->"),
];

/// Returns the page the definition renders.
fn render() -> String {
    let mut command = Cli::command().term_width(WIDTH).max_term_width(WIDTH);
    command.build();
    let mut out = HEADER.join("\n");
    out.push_str(
        "\n\n\
         # Command-line reference\n\n\
         **Audience:** operators and integrators. Every command and option of the\n\
         `ferrofed` binary, as `ferrofed <command> --help` prints it.\n\
         [Configuration](../operate/configuration.md) describes the configuration\n\
         every command reads.\n\n\
         <!-- toc -->\n\n",
    );
    section(&mut out, "ferrofed", &mut command);
    out.trim_end().to_owned() + "\n"
}

#[test]
fn the_book_holds_the_current_cli_reference() -> TestResult {
    let committed = std::fs::read_to_string(page_path())?;
    if committed != render() {
        return Err(format!(
            "{PAGE} is out of date: run `cargo nextest run -p ferrofed-server --test it \
             --run-ignored only cli_reference` and commit the page"
        )
        .into());
    }
    Ok(())
}

#[test]
#[ignore = "writes the book page; run on purpose after changing the CLI"]
fn write_the_cli_reference() -> TestResult {
    std::fs::write(page_path(), render())?;
    Ok(())
}
